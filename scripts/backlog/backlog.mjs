const task = (what, done, notes = '') =>
  `## Qué hacer\n${what}\n\n## Hecho cuando\n- [ ] ${done}\n${notes ? `\n## Notas\n${notes}\n` : ''}`;

const story = (context, ac, outOfScope = '', deps = '') =>
  `## Contexto\n${context}\n\n## Acceptance criteria\n${ac
    .map((a) => `- [ ] ${a}`)
    .join('\n')}\n${outOfScope ? `\n## Fuera de alcance\n${outOfScope}\n` : ''}${
    deps ? `\n## Dependencias\n${deps}\n` : ''
  }`;

